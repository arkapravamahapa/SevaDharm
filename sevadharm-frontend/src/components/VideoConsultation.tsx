import React, { useEffect, useRef, useState } from 'react';
import DailyIframe, { DailyCall } from '@daily-co/daily-js';
import { Video, PhoneOff, Loader2, ShieldCheck } from 'lucide-react';

interface VideoConsultationProps {
  roomUrl: string; // The unique meeting link generated by your FastAPI backend
  onLeaveCall: () => void;
}

export default function VideoConsultation({ roomUrl, onLeaveCall }: VideoConsultationProps) {
  const videoContainerRef = useRef<HTMLDivElement>(null);
  const [callObject, setCallObject] = useState<DailyCall | null>(null);
  const [hasJoined, setHasJoined] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!videoContainerRef.current) return;

    // Initialize the Daily.co Call Object and attach it to our div
    const callFrame = DailyIframe.createFrame(videoContainerRef.current, {
      iframeStyle: {
        width: '100%',
        height: '100%',
        border: '0',
        borderRadius: '16px',
      },
      showLeaveButton: true,
      showFullscreenButton: true,
    });

    setCallObject(callFrame);

    // Event Listeners for the call lifecycle
    callFrame.on('joined-meeting', () => setHasJoined(true));
    callFrame.on('left-meeting', () => {
      callFrame.destroy();
      onLeaveCall();
    });
    callFrame.on('error', (e) => {
      setError(e.errorMsg || 'An error occurred connecting to the secure room.');
    });

    // Clean up when the component unmounts
    return () => {
      callFrame.destroy();
    };
  }, [onLeaveCall]);

  const joinSecureRoom = async () => {
    if (!callObject) return;
    try {
      await callObject.join({ url: roomUrl });
    } catch (err: any) {
      setError(err.message || 'Failed to join the room.');
    }
  };

  return (
    <div className="bg-neutral-900 rounded-3xl overflow-hidden shadow-2xl border border-neutral-800 flex flex-col h-[600px] w-full max-w-4xl mx-auto relative">
      
      {/* Top Security Banner */}
      <div className="absolute top-0 left-0 w-full z-10 bg-gradient-to-b from-black/80 to-transparent px-6 py-4 flex items-center justify-between">
        <div className="flex items-center gap-2 text-emerald-400">
          <ShieldCheck className="w-5 h-5" />
          <span className="text-xs font-mono font-bold uppercase tracking-wider">End-to-End Encrypted</span>
        </div>
      </div>

      {/* Video Container (Daily.co iframe injects here) */}
      <div ref={videoContainerRef} className="flex-1 w-full relative z-0 bg-black">
        {/* Pre-join screen overlay */}
        {!hasJoined && !error && (
          <div className="absolute inset-0 flex flex-col items-center justify-center bg-neutral-900 z-20 space-y-6">
            <div className="p-4 bg-brand/20 rounded-full">
              <Video className="w-12 h-12 text-brand animate-pulse" />
            </div>
            <div className="text-center">
              <h3 className="text-white font-bold text-xl">Ready to join your consultation?</h3>
              <p className="text-neutral-400 text-sm mt-2">Camera and microphone access will be requested.</p>
            </div>
            <button 
              onClick={joinSecureRoom}
              className="px-8 py-3.5 bg-brand hover:bg-brand-hover text-white font-bold rounded-2xl transition-all flex items-center gap-2"
            >
              <Video className="w-5 h-5" />
              Join Secure Room
            </button>
          </div>
        )}

        {/* Error State */}
        {error && (
          <div className="absolute inset-0 flex flex-col items-center justify-center bg-neutral-900 z-20 space-y-4">
            <div className="text-red-500 font-bold">{error}</div>
            <button 
              onClick={onLeaveCall}
              className="px-6 py-2 bg-neutral-800 hover:bg-neutral-700 text-white rounded-xl text-sm font-bold"
            >
              Go Back
            </button>
          </div>
        )}
      </div>
    </div>
  );
}